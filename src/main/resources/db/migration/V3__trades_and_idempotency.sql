-- 2.0：一檔股票＝一個部位（holding），每次買進、賣出各記一筆交易（trade）。
-- 1.0 的每一筆持股轉成一筆買進：股數＝張數 × 1000，價格＝買進價。
-- 1.0 沒有記買進日期，用建立時間的台北日期代替，並標記 date_estimated。

ALTER TABLE holding ADD COLUMN version BIGINT DEFAULT 0 NOT NULL;

CREATE TABLE trade (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    holding_id      BIGINT         NOT NULL,
    side            VARCHAR(4)     NOT NULL,
    trade_date      DATE           NOT NULL,
    date_estimated  BOOLEAN        DEFAULT FALSE NOT NULL,
    shares          BIGINT         NOT NULL,
    price           DECIMAL(10, 2) NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    version         BIGINT DEFAULT 0 NOT NULL,
    CONSTRAINT fk_trade_holding FOREIGN KEY (holding_id) REFERENCES holding (id) ON DELETE CASCADE,
    CONSTRAINT ck_trade_side CHECK (side IN ('BUY', 'SELL')),
    CONSTRAINT ck_trade_shares CHECK (shares > 0),
    CONSTRAINT ck_trade_price CHECK (price > 0)
);

CREATE INDEX idx_trade_holding ON trade (holding_id, trade_date, id);

INSERT INTO trade (holding_id, side, trade_date, date_estimated, shares, price, created_at, updated_at, version)
SELECT id, 'BUY', CAST((created_at AT TIME ZONE 'Asia/Taipei') AS DATE), TRUE,
       CAST(lots AS BIGINT) * 1000, buy_price, created_at, updated_at, 0
FROM holding;

ALTER TABLE holding DROP CONSTRAINT ck_holding_lots;
ALTER TABLE holding DROP CONSTRAINT ck_holding_price;
ALTER TABLE holding DROP COLUMN lots;
ALTER TABLE holding DROP COLUMN buy_price;

-- App 2.0 網路不穩時會重送同一個請求：用 Idempotency-Key 記住第一次的結果，重送時直接回同一個結果
CREATE TABLE idempotency_record (
    idem_key         VARCHAR(100) NOT NULL PRIMARY KEY,
    fingerprint      VARCHAR(64)  NOT NULL,
    status           VARCHAR(12)  NOT NULL,
    response_status  INT,
    response_body    CHARACTER LARGE OBJECT,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_idem_status CHECK (status IN ('PROCESSING', 'DONE'))
);

CREATE INDEX idx_idem_created ON idempotency_record (created_at);

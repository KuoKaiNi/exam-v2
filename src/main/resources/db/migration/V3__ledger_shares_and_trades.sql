-- 2.0：股數改用「股」，每檔持股的買賣改存在 trade 表（一列一筆買進或賣出）。
-- 1.0 的每筆持股搬成一列「買進」交易：股數 = 張數 × 1000，成本與 1.0 的算法相同，
-- 因此 1.0 API 看到的盈虧與收益率不會因為升級而改變。
-- 1.0 沒有記買進日期，升級後 trade_date 為 NULL（API 顯示為 null，網頁顯示「未記錄」）。
ALTER TABLE holding DROP CONSTRAINT ck_holding_lots;
ALTER TABLE holding DROP CONSTRAINT ck_holding_buy_price;

CREATE TABLE trade (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    holding_id  BIGINT        NOT NULL,
    side        VARCHAR(4)    NOT NULL,
    trade_date  DATE,
    shares      INT           NOT NULL,
    price       DECIMAL(12,2) NOT NULL,
    amount      BIGINT        NOT NULL,
    fee         BIGINT        NOT NULL,
    tax         BIGINT        NOT NULL,
    CONSTRAINT fk_trade_holding FOREIGN KEY (holding_id) REFERENCES holding (id),
    CONSTRAINT ck_trade_side CHECK (side IN ('BUY', 'SELL')),
    CONSTRAINT ck_trade_shares CHECK (shares BETWEEN 1 AND 999999),
    CONSTRAINT ck_trade_price CHECK (price > 0)
);

-- 成交金額四捨五入到元，手續費 = 金額 × 0.1425%，無條件捨去，最低 20 元（與 2.0 程式相同）
INSERT INTO trade (holding_id, side, trade_date, shares, price, amount, fee, tax)
SELECT id,
       'BUY',
       NULL,
       lots * 1000,
       buy_price,
       CAST(ROUND(lots * 1000 * buy_price, 0) AS BIGINT),
       CAST(GREATEST(20, FLOOR(ROUND(lots * 1000 * buy_price, 0) * 0.001425)) AS BIGINT),
       0
FROM holding;

ALTER TABLE holding DROP COLUMN lots;
ALTER TABLE holding DROP COLUMN buy_price;

